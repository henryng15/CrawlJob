#!/usr/bin/env bash
# One command from nothing to a running system.
#
#   ./deploy/deploy.sh
#
# Builds the machine, copies the source over Tailscale, writes configuration,
# migrates, starts everything, and verifies it answers. Re-running is safe: it
# converges rather than rebuilding.
#
# Three design decisions worth knowing:
#
# * **Secrets are generated once, locally, and reused.** deploy/secrets.env is
#   gitignored and never regenerated. APP_ENCRYPTION_KEY in particular must
#   survive an instance rebuild, or every backup taken before the rebuild becomes
#   unreadable — which is the failure that turns a bad afternoon into a lost year.
#
# * **The source goes over Tailscale, not through a git remote.** This repo is
#   private and the source is already on your machine. A deploy key, a registry
#   or a public mirror would each be one more secret to manage for no gain.
#
# * **Capacity failures retry across availability domains.** OCI Always Free A1
#   is genuinely scarce; "Out of host capacity" is the expected first answer, not
#   a mistake in the configuration.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
readonly REPO_ROOT
readonly TF_DIR="$REPO_ROOT/infra/terraform"
readonly SECRETS="$REPO_ROOT/deploy/secrets.env"
readonly REMOTE_USER="ubuntu"
readonly REMOTE_DIR="/opt/internship-ops"
readonly HOSTNAME_ON_TAILNET="internshipops"

# Availability domains to try, in order, when capacity is refused.
readonly AD_ATTEMPTS=(0 1 2)

bold() { printf '\033[1m%s\033[0m\n' "$*"; }
info() { printf '  %s\n' "$*"; }
warn() { printf '\033[33m  %s\033[0m\n' "$*" >&2; }
die()  { printf '\033[31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

step() { printf '\n\033[1m==> %s\033[0m\n' "$*"; }


# ----------------------------------------------------------------- preflight

preflight() {
  step "Preflight"

  local missing=()
  for tool in terraform tailscale rsync ssh; do
    command -v "$tool" >/dev/null || missing+=("$tool")
  done
  if [[ ${#missing[@]} -gt 0 ]]; then
    die "install these first: ${missing[*]}
  terraform  https://developer.hashicorp.com/terraform/install
  tailscale  https://tailscale.com/download"
  fi
  info "tools present"

  [[ -f "$TF_DIR/terraform.tfvars" ]] || die \
    "no $TF_DIR/terraform.tfvars.
  cp $TF_DIR/terraform.tfvars.example $TF_DIR/terraform.tfvars
  then fill it in — see infra/terraform/README.md"

  # A tfvars still holding the example values produces a confusing OCI error
  # several minutes later. Catch it here instead.
  if grep -q 'ocid1.tenancy.oc1..aaaa\.\.\.' "$TF_DIR/terraform.tfvars"; then
    die "terraform.tfvars still has the example OCIDs in it"
  fi
  info "terraform.tfvars looks filled in"

  if ! tailscale status >/dev/null 2>&1; then
    die "this machine is not on your tailnet. Run: sudo tailscale up"
  fi
  info "tailscale is up on this machine"

  if ! grep -q 'tailscale_auth_key' "$TF_DIR/terraform.tfvars" ||
     grep -qE '^\s*#\s*tailscale_auth_key' "$TF_DIR/terraform.tfvars"; then
    warn "tailscale_auth_key is not set in terraform.tfvars."
    warn "Without it the instance cannot join the tailnet on its own, and this"
    warn "script cannot reach it. Create one (Reusable + Tagged + Pre-approved):"
    warn "  https://login.tailscale.com/admin/settings/keys"
    die "set tailscale_auth_key, then run this again"
  fi
  info "tailscale auth key is configured"
}


# ------------------------------------------------------------------ secrets

ensure_secrets() {
  step "Secrets"

  if [[ -f "$SECRETS" ]]; then
    info "reusing $SECRETS"
    # Deliberately not regenerated. See the note at the top of this file.
    return
  fi

  local key_a key_b admin_password
  key_a="$(python3 -c 'import secrets; print(secrets.token_urlsafe(48))')"
  key_b="$(python3 -c 'import secrets; print(secrets.token_urlsafe(48))')"
  admin_password="$(python3 -c 'import secrets; print(secrets.token_urlsafe(18))')"

  umask 077
  cat > "$SECRETS" <<EOF
# Generated by deploy/deploy.sh. Gitignored. Back this file up somewhere other
# than this machine.
#
# APP_ENCRYPTION_KEY encrypts the database backups and the Gmail token. Lose it
# and both become unreadable — no recovery, by design.
APP_SECRET_KEY=$key_a
APP_ENCRYPTION_KEY=$key_b
ADMIN_USERNAME=admin
ADMIN_PASSWORD=$admin_password
EOF
  chmod 600 "$SECRETS"

  bold "Generated $SECRETS"
  warn "Back it up NOW, somewhere other than this laptop."
  warn "Losing APP_ENCRYPTION_KEY makes every backup unreadable."
}


# --------------------------------------------------------------- provisioning

provision() {
  step "Provisioning the machine"

  terraform -chdir="$TF_DIR" init -input=false >/dev/null
  info "terraform initialised"

  # A1 capacity is scarce and varies by availability domain, so a refusal in one
  # is not a refusal everywhere. This is the documented first thing to try.
  local ad
  for ad in "${AD_ATTEMPTS[@]}"; do
    info "trying availability domain $ad"
    if terraform -chdir="$TF_DIR" apply -auto-approve -input=false \
         -var "availability_domain_index=$ad" 2>&1 | tee /tmp/tf-apply.log | tail -5; then
      info "instance is up"
      return 0
    fi

    if grep -qi "out of host capacity\|capacity" /tmp/tf-apply.log; then
      warn "no capacity in domain $ad"
      continue
    fi

    die "terraform failed for a reason other than capacity. See /tmp/tf-apply.log"
  done

  cat >&2 <<'EOT'

No Ampere capacity in any availability domain right now. This is normal and not
a fault in the configuration. In order of effectiveness:

  1. Upgrade the tenancy to Pay As You Go. Free-tier resources still cost $0,
     but paid tenancies are served first. This is the biggest single change.
  2. Retry on a loop. Capacity does free up:
       while ! ./deploy/deploy.sh; do sleep 300; done
  3. If you have not signed up yet, note that the home region is permanent and
     Frankfurt and Singapore have markedly better A1 availability than US East.

EOT
  exit 1
}


# -------------------------------------------------------------------- deploy

wait_for_tailnet() {
  step "Waiting for the instance to join the tailnet"

  local attempt
  for attempt in $(seq 1 60); do
    if tailscale status 2>/dev/null | grep -q "$HOSTNAME_ON_TAILNET"; then
      info "the instance is on the tailnet"
      # SSH can lag the tailnet by a few seconds.
      for _ in $(seq 1 30); do
        if ssh -o StrictHostKeyChecking=accept-new -o ConnectTimeout=5 \
             "$REMOTE_USER@$HOSTNAME_ON_TAILNET" true 2>/dev/null; then
          info "ssh works"
          return 0
        fi
        sleep 5
      done
      die "the instance is on the tailnet but ssh does not answer"
    fi
    [[ $((attempt % 6)) -eq 0 ]] && info "still waiting (${attempt}0s)"
    sleep 10
  done

  die "the instance never appeared on the tailnet. Check the auth key was
  Reusable and Pre-approved, then look at the console serial log."
}

remote() { ssh -o StrictHostKeyChecking=accept-new "$REMOTE_USER@$HOSTNAME_ON_TAILNET" "$@"; }

copy_source() {
  step "Copying the source"

  remote "sudo mkdir -p $REMOTE_DIR && sudo chown $REMOTE_USER:$REMOTE_USER $REMOTE_DIR"

  # --delete so a file removed locally is removed there too; without it a stale
  # module lingers and the running code stops matching the code you are reading.
  rsync -az --delete \
    --exclude '.git' --exclude '.venv' --exclude '__pycache__' \
    --exclude '.pytest_cache' --exclude '.ruff_cache' --exclude '.mypy_cache' \
    --exclude 'infra/terraform/.terraform' --exclude 'deploy/secrets.env' \
    --exclude '.env' \
    "$REPO_ROOT/" "$REMOTE_USER@$HOSTNAME_ON_TAILNET:$REMOTE_DIR/"
  info "source copied to $REMOTE_DIR"
}

write_env() {
  step "Writing configuration"

  # shellcheck source=/dev/null
  set -a
  # shellcheck source=/dev/null
  source "$SECRETS"
  set +a

  local anthropic_key="" groq_key=""
  if [[ -f "$REPO_ROOT/.env" ]]; then
    anthropic_key="$(grep -E '^ANTHROPIC_API_KEY=.' "$REPO_ROOT/.env" | cut -d= -f2- || true)"
    groq_key="$(grep -E '^GROQ_API_KEY=.' "$REPO_ROOT/.env" | cut -d= -f2- || true)"
  fi
  [[ -n "$anthropic_key" ]] && info "carrying over ANTHROPIC_API_KEY from your local .env"
  [[ -n "$groq_key" ]] && info "carrying over GROQ_API_KEY from your local .env"

  # Routed needs both keys. With only one, fall back rather than writing a
  # config that refuses to start — a deploy that boots paused is recoverable,
  # one that crash-loops on settings validation is not.
  local llm_provider=null
  if [[ -n "$anthropic_key" && -n "$groq_key" ]]; then
    llm_provider=routed
  elif [[ -n "$anthropic_key" ]]; then
    llm_provider=anthropic
  fi

  local password_hash
  password_hash="$(cd "$REPO_ROOT" && uv run python -c "
from app.web.security import hash_password
print(hash_password('$ADMIN_PASSWORD'))" 2>/dev/null)" ||
    die "could not hash the admin password locally. Is 'uv sync' done?"

  # An argon2 hash is $argon2id$v=19$m=...$...: a '$' at every field boundary,
  # and on the way to the container it passes two separate things that each
  # read '$' as a variable reference.
  #
  #   1. The ENVFILE heredoc below is deliberately unquoted, so that
  #      $DB_PASSWORD is read on the instance. Under `set -u` an unescaped hash
  #      aborts the step outright: "argon2id: unbound variable".
  #   2. Docker Compose interpolates the project .env file. A hash escaped only
  #      for (1) survives to disk intact and then arrives in the container with
  #      every field deleted — 97 characters become 63, and the only symptom is
  #      that the correct password is rejected at /login. Nothing logs a cause.
  #
  # So each '$' is written as '$$': the heredoc turns '\$\$' into '$$', and
  # Compose turns '$$' back into '$'. The .env on disk holds '$$' by design.
  # Read the value with `docker compose exec web printenv`, not with grep.
  local password_hash_escaped="${password_hash//\$/\\\$\\\$}"

  local db_password
  db_password="$(python3 -c 'import secrets; print(secrets.token_urlsafe(24))')"

  # The database password is generated per deployment and stored only on the
  # instance, in a Docker secret. It never needs to leave the machine.
  remote "bash -s" <<EOF
set -euo pipefail
# 0711, not 0700. The web container runs as uid 10001 and mounts this
# directory read-only for one purpose: asking whether the Gmail token is
# there yet, so /setup can tick a box. Traverse-only grants exactly that —
# stat a known filename — while listing stays denied and the files inside
# stay 0600. At 0700 the stat raises PermissionError and /setup returns 500.
sudo install -d -o $REMOTE_USER -g $REMOTE_USER -m 0711 /data/internship-ops/secrets
if [ ! -s /data/internship-ops/secrets/postgres_password ]; then
  printf '%s' '$db_password' > /data/internship-ops/secrets/postgres_password
  chmod 600 /data/internship-ops/secrets/postgres_password
fi
DB_PASSWORD="\$(cat /data/internship-ops/secrets/postgres_password)"

umask 077
cat > $REMOTE_DIR/.env <<ENVFILE
APP_ENV=production
APP_TIMEZONE=America/New_York
APP_BASE_URL=https://$HOSTNAME_ON_TAILNET.\$(tailscale status --json | python3 -c 'import json,sys; print(json.load(sys.stdin)["MagicDNSSuffix"])')
APP_SECRET_KEY=$APP_SECRET_KEY
APP_ENCRYPTION_KEY=$APP_ENCRYPTION_KEY

ADMIN_USERNAME=$ADMIN_USERNAME
ADMIN_PASSWORD_HASH=$password_hash_escaped
SESSION_COOKIE_SECURE=true
SESSION_IDLE_TIMEOUT_MINUTES=60

DATABASE_URL=postgresql+psycopg://internship_ops:\$DB_PASSWORD@postgres:5432/internship_ops
DATA_DIR=/data/internship-ops

LLM_PROVIDER=$llm_provider
ANTHROPIC_API_KEY=$anthropic_key
GROQ_API_KEY=$groq_key
LLM_CLASSIFICATION_MODEL=claude-haiku-4-5-20251001
LLM_WRITING_MODEL=claude-sonnet-5
GROQ_MODEL=llama-3.3-70b-versatile
LLM_MONTHLY_BUDGET_USD=15
LLM_BATCH_TIMEOUT_HOURS=24

GMAIL_TOKEN_PATH=/data/internship-ops/secrets/gmail_token.enc

PIPELINE_ENABLED=false
BASE_RESUME_STATUS=MISSING
ORCHESTRATION_TIMES=08:00,14:00

MAX_PREPARED_APPLICATIONS_PER_DAY=30
MAX_BROWSER_WORKERS=2
MAX_LIVE_SESSIONS=2
LIVE_SESSION_TTL_HOURS=8
PREPARED_APPLICATION_TTL_HOURS=24

OUTREACH_INITIAL_DAILY_LIMIT=3
OUTREACH_MAX_DAILY_LIMIT=5
OUTREACH_DELAY_BUSINESS_DAYS=2
OUTREACH_MAX_PER_COMPANY_30D=2
OUTREACH_MAX_FOLLOWUPS=1

MINIMUM_FIT_SCORE=72
MAX_ROLE_AGE_DAYS=21
MAX_ROLE_AGE_HOURS=24
MAX_ACTIVE_APPLICATIONS_PER_COMPANY=2
# Empty means "use the list shipped in app/services/filters.py", which is the
# sixteen role variants. Set these only to override it.
ROLE_TITLE_VARIANTS=
ROLE_REJECT_TERMS=

PUBLIC_JOB_SCRAPING_ENABLED=false

AUTO_SUBMIT_ENABLED=false
AUTO_SEND_EMAIL_ENABLED=false
CAPTCHA_BYPASS_ENABLED=false
LINKEDIN_AUTOMATION_ENABLED=false
ENVFILE
chmod 600 $REMOTE_DIR/.env
EOF
  info ".env written on the instance (mode 600)"
}

start_services() {
  step "Building and starting"
  info "the first build takes 5-10 minutes on an A1"

  remote "bash -s" <<EOF
set -euo pipefail
cd $REMOTE_DIR
# The migrate service runs to completion before web and worker start, so two
# replicas can never race to migrate the same database.
docker compose -f docker-compose.prod.yml up -d --build
EOF
  info "containers started"

  step "Publishing over Tailscale"
  # Serve, never Funnel. Funnel would put this on the public internet, which is
  # the one thing §23.1 forbids.
  #
  # When Serve has not been enabled for the tailnet, `tailscale serve` prints a
  # URL and then blocks until somebody visits it — forever, with no further
  # output. Run unattended that is indistinguishable from a hang, so bound it
  # and print the URL rather than waiting behind it.
  local serve_out
  if ! serve_out="$(remote "sudo timeout 30 tailscale serve --bg 8080 </dev/null 2>&1")"; then
    local enable_url
    enable_url="$(grep -o 'https://login.tailscale.com/[^ ]*' <<<"$serve_out" || true)"
    if [[ -n "$enable_url" ]]; then
      cat >&2 <<EOT

Serve is not enabled for your tailnet. Everything else is deployed and healthy;
this is the last switch, and only you can flip it. Open this, approve, then run
this script again:

  $enable_url

EOT
      exit 1
    fi
    die "tailscale serve failed:
$serve_out"
  fi
  info "https on the tailnet only; Funnel is off"
}

verify() {
  step "Verifying"

  local attempt
  for attempt in $(seq 1 30); do
    if remote "curl -sf http://127.0.0.1:8080/health/ready" >/tmp/health.json 2>/dev/null; then
      break
    fi
    sleep 10
  done

  if ! grep -q '"database":"ok"' /tmp/health.json 2>/dev/null; then
    remote "cd $REMOTE_DIR && docker compose -f docker-compose.prod.yml ps" || true
    die "the app did not come up healthy. Look at:
  ssh $REMOTE_USER@$HOSTNAME_ON_TAILNET
  cd $REMOTE_DIR && docker compose -f docker-compose.prod.yml logs web --tail 100"
  fi
  info "database reachable"

  # The two guarantees, asserted against the running system rather than trusted.
  grep -q '"auto_submit_enabled":false' /tmp/health.json ||
    die "auto_submit_enabled is not false on the running system"
  grep -q '"auto_send_email_enabled":false' /tmp/health.json ||
    die "auto_send_email_enabled is not false on the running system"
  info "kill switches confirmed off on the running system"
}


# --------------------------------------------------------------------- main

main() {
  preflight
  ensure_secrets
  provision
  wait_for_tailnet
  copy_source
  write_env
  start_services
  verify

  # shellcheck source=/dev/null
  set -a
  # shellcheck source=/dev/null
  source "$SECRETS"
  set +a
  local suffix
  suffix="$(tailscale status --json | python3 -c 'import json,sys; print(json.load(sys.stdin)["MagicDNSSuffix"])')"

  cat <<EOT

$(bold "Done.")

  URL       https://$HOSTNAME_ON_TAILNET.$suffix
  Username  $ADMIN_USERNAME
  Password  $ADMIN_PASSWORD

  (also in $SECRETS — back that file up)

Next, in the browser:

  1. Open the URL and sign in.
  2. Go to /setup. It lists exactly what is still missing.
  3. Add a job board under Settings.

Then, from this machine:

  ./deploy/push-resume.sh ~/resume.pdf     # resume, facts, and confirmation
  ./deploy/push-gmail.sh                   # one-time Gmail authorisation

To redeploy after changing code, run this script again. It converges.
EOT
}

main "$@"
